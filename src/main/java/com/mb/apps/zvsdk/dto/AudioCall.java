
package com.mb.apps.zvsdk.dto;

public class AudioCall {
    private String call_number;
    private String call_type;
    private String zoom_number;

    public String getCall_number() { return call_number; }
    public void setCall_number(String call_number) { this.call_number = call_number; }

    public String getCall_type() { return call_type; }
    public void setCall_type(String call_type) { this.call_type = call_type; }

    public String getZoom_number() { return zoom_number; }
    public void setZoom_number(String zoom_number) { this.zoom_number = zoom_number; }
}
